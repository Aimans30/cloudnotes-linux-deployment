"""Create a .env file with freshly generated secrets.

Usage:  python scripts/generate_env.py [--force]

Refuses to overwrite an existing .env unless --force is given. Secrets are
written only to .env (git-ignored) and are never printed.
"""

import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV_PATH = ROOT / ".env"
DB_USER = "cloudnotes_user"
DB_NAME = "cloudnotes"


def build_env_text():
    # token_hex yields URL-safe characters, so the password needs no URL escaping.
    app_password = secrets.token_hex(24)
    admin_password = secrets.token_hex(24)
    secret_key = secrets.token_urlsafe(48)
    return "\n".join(
        [
            "# Generated by scripts/generate_env.py. Git-ignored. Do not commit.",
            f"SECRET_KEY={secret_key}",
            "FLASK_ENV=production",
            "GUNICORN_WORKERS=2",
            f"DATABASE_URL=postgresql://{DB_USER}:{app_password}@db:5432/{DB_NAME}",
            f"APP_DB_USER={DB_USER}",
            f"APP_DB_PASSWORD={app_password}",
            "POSTGRES_ADMIN_USER=cloudnotes_admin",
            f"POSTGRES_ADMIN_PASSWORD={admin_password}",
            "",
        ]
    )


def main():
    if ENV_PATH.exists() and "--force" not in sys.argv:
        print(".env already exists. Re-run with --force to replace it.", file=sys.stderr)
        return 1
    ENV_PATH.write_text(build_env_text(), encoding="utf-8")
    print(f"Wrote {ENV_PATH} with generated secrets.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
